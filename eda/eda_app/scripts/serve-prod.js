'use strict';

/**
 * Serve a production build (multi-locale) locally, the same way Apache/nginx does it:
 *
 *   - static files from `dist/app-eda`
 *   - `/edapi/*`   → proxied to the API (default http://localhost:8667), prefix stripped
 *   - SPA fallback → the index.html of the requested locale (`/es/...` → `es/index.html`)
 *   - `/`          → the root index.html (the one that redirects by browser language)
 *
 * Usage:
 *   npm run build:prod      # first: generates dist/app-eda/{es,ca,en,gl} + index.html
 *   npm run serve:prod      # then: http://localhost:4300/
 *
 * Environment variables (all optional):
 *   PORT=4300               port to listen on
 *   API_URL=http://localhost:8667   API base URL to proxy /edapi to
 *   SERVE_DIST=dist/app-eda         directory to serve
 */

const http = require('http');
const fs = require('fs');
const path = require('path');
const url = require('url');

const PORT = parseInt(process.env.PORT || '4300', 10);
const API_URL = process.env.API_URL || 'http://localhost:8667';
const DIST_DIR = path.resolve(__dirname, '..', process.env.SERVE_DIST || 'dist/app-eda');

const api = new URL(API_URL);

/** Locales generated by `ng build --localize` (folders of the dist that have their own index.html). */
const LOCALES = fs
  .readdirSync(DIST_DIR, { withFileTypes: true })
  .filter(entry => entry.isDirectory() && fs.existsSync(path.join(DIST_DIR, entry.name, 'index.html')))
  .map(entry => entry.name);

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.mjs': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
  '.ico': 'image/x-icon',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.svg': 'image/svg+xml',
  '.webp': 'image/webp',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.otf': 'font/otf',
  '.eot': 'application/vnd.ms-fontobject',
  '.txt': 'text/plain; charset=utf-8',
  '.xlf': 'application/xml; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8',
  '.pdf': 'application/pdf',
};

if (!fs.existsSync(DIST_DIR)) {
  console.error(`\x1b[31mNo existe ${DIST_DIR}\x1b[0m`);
  console.error('Compila primero con localización:  npm run build:prod');
  process.exit(1);
}

/** Resolves a URL path inside DIST_DIR, preventing directory traversal. */
function safePath(urlPath) {
  const clean = decodeURIComponent(urlPath.split('?')[0]);
  const resolved = path.resolve(DIST_DIR, '.' + clean);
  return resolved.startsWith(DIST_DIR) ? resolved : null;
}

function sendFile(res, filePath) {
  const ext = path.extname(filePath).toLowerCase();
  const type = MIME_TYPES[ext] || 'application/octet-stream';
  res.writeHead(200, {
    'Content-Type': type,
    'Cache-Control': 'no-cache, no-store, must-revalidate',
  });
  fs.createReadStream(filePath).pipe(res);
}

function sendPlain(res, status, message) {
  res.writeHead(status, { 'Content-Type': 'text/plain; charset=utf-8' });
  res.end(message);
}

/** index.html to use as SPA fallback for the requested path. */
function spaIndex(urlPath) {
  const first = urlPath.split('?')[0].split('/').filter(Boolean)[0];
  const localeIndex = first && LOCALES.includes(first) ? path.join(DIST_DIR, first, 'index.html') : null;
  if (localeIndex && fs.existsSync(localeIndex)) return localeIndex;
  return path.join(DIST_DIR, 'index.html');
}

function proxyApi(req, res) {
  const targetPath = req.url.replace(/^\/edapi/, '') || '/';
  const headers = { ...req.headers, host: `${api.hostname}:${api.port || 80}` };

  const proxyReq = http.request(
    {
      hostname: api.hostname,
      port: api.port || 80,
      path: targetPath,
      method: req.method,
      headers,
    },
    apiRes => {
      res.writeHead(apiRes.statusCode || 502, apiRes.headers);
      apiRes.pipe(res);
    }
  );

  proxyReq.on('error', err => {
    console.error(`[serve-prod] proxy error ${req.method} ${targetPath}:`, err.message);
    if (!res.headersSent) sendPlain(res, 502, `No se ha podido contactar con la API en ${API_URL}`);
  });

  req.pipe(proxyReq);
}

const server = http.createServer((req, res) => {
  const urlPath = (url.parse(req.url).pathname) || '/';

  if (urlPath === '/edapi' || urlPath.startsWith('/edapi/')) {
    return proxyApi(req, res);
  }

  if (req.method !== 'GET' && req.method !== 'HEAD') {
    return sendPlain(res, 405, 'Method not allowed');
  }

  // Root: the index.html that redirects to the browser/user language.
  if (urlPath === '/' || urlPath === '/index.html') {
    return sendFile(res, path.join(DIST_DIR, 'index.html'));
  }

  // Existing file (js, css, assets, or an explicit index.html).
  const filePath = safePath(urlPath);
  if (filePath && fs.existsSync(filePath) && fs.statSync(filePath).isFile()) {
    return sendFile(res, filePath);
  }

  // Directory without trailing slash → add it so relative assets resolve.
  if (filePath && fs.existsSync(filePath) && fs.statSync(filePath).isDirectory() && !urlPath.endsWith('/')) {
    res.writeHead(301, { Location: `${urlPath}/` });
    return res.end();
  }

  // SPA route → the index.html of its locale.
  const index = spaIndex(urlPath);
  if (fs.existsSync(index)) return sendFile(res, index);

  return sendPlain(res, 404, 'Not found');
});

server.listen(PORT, () => {
  console.log(`\n\x1b[34m=====\x1b[0m Build de producción servido en \x1b[32mhttp://localhost:${PORT}/\x1b[0m`);
  console.log(`      Dist: \x1b[36m${DIST_DIR}\x1b[0m`);
  console.log(`      API (/edapi): \x1b[36m${API_URL}\x1b[0m`);
  console.log(`      Idiomas: ${LOCALES.join(', ')} (se ofrecen los de ENABLED_LANGUAGES)\n`);
});
