'use strict';

module.exports = {
    requiredFields: ['type', 'pluginFile', 'pluginExport'],

    buildOutput(plugins) {
        const imports = plugins
            .map((p) => `import { ${p.pluginExport} } from './${p.dir}/${p.pluginFile.replace(/^\.\//, '')}';`)
            .join('\n');

        const entries = plugins
            .map((p) => `    ${p.pluginExport},`)
            .join('\n');

        return `// AUTO-GENERATED by scripts/generate-plugins.js — do not edit by hand.
// To add a new authentication plugin, create a folder in
// auth-plugins with its plugin.meta.ts and class, then re-run
// \`npm start\` / \`npm run build:prod\`.
import { IAuthPluginCtor } from './auth-plugin.interface';
${imports}

export const AUTH_PLUGINS: IAuthPluginCtor[] = [
${entries}
];
`;
    },
};
